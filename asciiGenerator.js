function generateCustomPattern(text) {
  const normalizedText = text.toUpperCase();
  const lines = ['', '', '', '', ''];

  for (let i = 0; i < normalizedText.length; i++) {
    const char = normalizedText[i];
    const glyph = GLYPHS[char] || GLYPHS['fallback'];

    for (let row = 0; row < 5; row++) {
      lines[row] += glyph[row] + '  ';
    }
  }

  return lines.join('\n');
}

